/**
 * 마크다운 한 덩이 → **한 줄 평문**. 대화 지도의 차례 이름처럼 한 줄 요약에 쓴다(디자인 25차).
 *
 * 원문을 그대로 한 줄로 이으면 `## 시험51 제목 - **굵게** 와 \`코드\` - [ ] 할 일 > 인용 | 가 | 나` 처럼 기호가 글보다
 * 먼저 보였다 — 좁은 칸에서는 기호만 남고 잘렸다. 뜻을 가진 글만 남긴다: 제목·인용·목록·체크 표시와 코드 울타리를 떼고,
 * 링크·그림은 보이는 글만, 강조·코드 기호와 표의 세로줄은 지운다. 서버의 context_store._plain_line 과 같은 규칙이다
 * (컨텍스트 화면의 세션 미리보기).
 */
export function plainLine(md: string): string {
  const lines = (md || "").split(/\r?\n/).map((l) =>
    l
      .replace(/^\s*```.*$/, "")                     // 코드 울타리 줄(안의 코드는 남긴다)
      .replace(/^\s*\|?\s*:?-{3,}:?\s*(\|\s*:?-{3,}:?\s*)*\|?\s*$/, "") // 표 구분 줄
      .replace(/^\s*(?:>\s?)+/, "")                   // 인용
      .replace(/^\s*#{1,6}\s+/, "")                   // 제목
      .replace(/^\s*(?:[-*+]|\d{1,9}[.)])\s+/, "")    // 목록 표시
      .replace(/^\s*\[[ xX]\]\s+/, ""),              // 체크 표시
  );
  return lines.join(" ")
    .replace(/!?\[\[([^\]|#]+)(?:[#|][^\]]*)?\]\]/g, "$1") // 위키링크·임베드 → 제목
    .replace(/!\[([^\]]*)\]\([^)]*\)/g, "$1")         // 그림 → 대체 글
    .replace(/\[([^\]]+)\]\((?:[^)(]|\([^)]*\))*\)/g, "$1") // 링크 → 보이는 글
    .replace(/\*\*|__|~~|==/g, "")                     // 굵게·취소·형광
    .replace(/(^|[^\w*])[*_](?=\S)([^*_]*?\S)[*_](?![\w*])/g, "$1$2") // 기울임
    .replace(/`+/g, "")                                // 코드 기호
    .replace(/\s*\|\s*/g, " ")                         // 표 세로줄
    .replace(/\s+/g, " ")
    .trim();
}
