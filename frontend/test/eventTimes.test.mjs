/**
 * 일정 편집창 — 시작을 옮기면 종료가 따라오는가.
 *
 * 돌리는 법:
 *   node --experimental-strip-types --import ./test/tsResolve.mjs --test test/eventTimes.test.mjs
 */
import assert from "node:assert/strict";
import { test } from "node:test";
import { DEFAULT_MINUTES, followEnd } from "../src/lib/eventTimes.ts";

test("시작을 바꾸면 종료가 한 시간 뒤로", () => {
  // 사용자의 예: 시작을 오후 10시로 하면 종료는 오후 11시
  assert.equal(followEnd("2026-09-24T22:00", "2026-09-24T09:00", "2026-09-24T10:00"),
               "2026-09-24T23:00");
  // 새로 만드는 중이라 원래 값이 없을 때도 한 시간
  assert.equal(followEnd("2026-09-24T22:00", "", ""), "2026-09-24T23:00");
  assert.equal(DEFAULT_MINUTES, 60);
});

test("일부러 길게 잡아 둔 일정은 그 길이를 지킨다", () => {
  // 2시간짜리를 옮기면 2시간 그대로. 1시간으로 줄여 버리면 고쳐 둔 것을 빼앗는다.
  assert.equal(followEnd("2026-09-24T13:00", "2026-09-24T09:00", "2026-09-24T11:00"),
               "2026-09-24T15:00");
  // 거꾸로 된 값(종료가 시작보다 앞)은 한 시간으로 바로잡는다
  assert.equal(followEnd("2026-09-24T13:00", "2026-09-24T09:00", "2026-09-24T08:00"),
               "2026-09-24T14:00");
});

test("날짜를 넘어가도 옳다", () => {
  assert.equal(followEnd("2026-09-24T23:30", "2026-09-24T09:00", "2026-09-24T10:00"),
               "2026-09-25T00:30");
  // 서머타임 없는 한국 기준이지만, 지역 시각 그대로 셈해야 날짜가 안 밀린다
  assert.equal(followEnd("2026-12-31T23:00", "2026-12-31T09:00", "2026-12-31T10:00"),
               "2027-01-01T00:00");
});

test("종일 일정은 시각을 만들지 않는다", () => {
  // 시작일을 뒤로 옮기면 종료일도 따라온다(앞설 수 없다)
  assert.equal(followEnd("2026-09-26T09:00", "2026-09-24T09:00", "2026-09-25T10:00", true)
                 .slice(0, 10), "2026-09-26");
  // 여러 날짜리는 그대로 둔다
  assert.equal(followEnd("2026-09-24T09:00", "2026-09-24T09:00", "2026-09-27T10:00", true),
               "2026-09-27T10:00");
});

test("시작이 비면 종료를 건드리지 않는다", () => {
  assert.equal(followEnd("", "2026-09-24T09:00", "2026-09-24T10:00"), "2026-09-24T10:00");
});
