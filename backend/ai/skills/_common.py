from __future__ import annotations

import re

# 민감 문서 판정은 backend/sensitive.py 한 곳에 있다(링크·검색도 같은 것을 쓴다).
from ...sensitive import SENSITIVE_KEYWORDS, is_sensitive as _is_sensitive  # noqa: F401

_MAX_READ = 20000


#: "문서로 남겨 달라"고 실제로 말했는가.
#:
#: 프롬프트가 "정리한 결과는 문서로 남깁니다"라고 무조건 시키고 있어서, 그냥
#: "요약해 줘"에도 2번 중 2번 문서를 만들었다(실측). 문구를 고쳤더니 이번에는
#: 반대로 **"'요약' 문서로 만들어줘"라는 분명한 요청을 2번 중 1번 무시**했다.
#: 프롬프트로 양쪽에 실패했으므로 서버가 직접 본다(단어장 71차와 같은 교훈).
#: "노트"·"메모" 는 이 앱이 문서를 부르는 말이다("계획 노트 만들고 일정 잡아줘").
ASK_TO_SAVE = re.compile(
    r"문서|파일|노트|메모|저장|남겨|남기|작성|기록해|기록으로|적어\s?(?:둬|놔|두)"
    r"|정리해서 .*(만들|남)|만들어 ?줘|만들어 ?주|만들자|만들고|만들어서|추가해|붙여|이어 ?써|덮어"
    r"|\bdoc\b|\bsave\b|\bwrite\b|\bfile\b"
)


def asked_to_save(ctx) -> bool:
    """이번 차례에 사람이 '문서로 남겨 달라'고 했는가.

    안 했으면 만들지 않고 **본문을 그대로 돌려준다** — 모델은 그것을 말로 답하면
    된다. 잘못 판단해도 손해가 다르다: 안 만들면 사용자가 한 번 더 말하면 되고,
    잘못 만들면 만든 적 없는 문서가 쌓이고 같은 이름이면 앞의 것을 덮어쓴다.

    화면이 부른 것(user_message 가 비어 있는 경우)은 사용자가 단추를 눌러
    시킨 일이므로 막지 않는다.

    **비서가 바로 앞에서 저장을 물었으면, 거절이 아닌 짧은 대답은 부탁이다.** 부탁 없이
    쓰려 하면 비서가 "문서로 남길까요?" 라고 묻도록 되어 있는데, 예전에는 사람의 "네" 에
    저장을 뜻하는 낱말이 없어서 또 막혔다. "네" 만 받아 주면 이번엔 비서가 "어떤 이름으로
    저장할까요?" 라고 되묻고, 사람이 "피보나치로" 라고 답하면 또 막혔다(실모델 실측) —
    물어 놓고 대답을 받을 수 없는 막다른 길이었다.
    """
    msg = str(getattr(ctx, "user_message", "") or "")
    if not msg.strip() or ASK_TO_SAVE.search(msg):
        return True
    prev = str(getattr(ctx, "prev_answer", "") or "")[-300:]
    return (bool(_OFFERED.search(prev)) and len(msg.strip()) <= _MAX_REPLY
            and not _REFUSED.match(msg))


#: 비서가 저장을 물었는가("문서로 남길까요?", "어떤 이름으로 저장할까요?", "저장해 드릴까요?").
_OFFERED = re.compile(r"(?:저장|남기|남길|남겨|문서로|파일로)[^.?!\n]{0,40}(?:까요|할까|드릴까)")
#: 거절("아니요", "괜찮아", "됐어", "필요 없어", "no").
_REFUSED = re.compile(
    r"^\s*(?:아니|아뇨|아닙니다|싫|됐어|됐습니다|괜찮아|괜찮습니다|필요\s?없|하지\s?마|말아|no\b|nope|nah)",
    re.I,
)
#: 물음에 대한 대답으로 볼 길이. 이름·예/아니오는 이 안에 든다. 길면 다른 이야기를 꺼낸 것이다.
_MAX_REPLY = 30
